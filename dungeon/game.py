# --- Заголовок ------------------------------------
title = "РАЗБИТЫЙ МОСТ"
frame = "=" * 19
print(frame)
print(" " + title + " ")
print(frame)
print()

# --- Знакомство с героем --------------------------
print("Как зовут героя?")
hero_name = input()
print(f"Добро пожаловать, {hero_name}!")
print("Перед тобой разбитый мост. Внизу пропасть, и дует холодный ветер.")
print()

# --- Настройка героя ---------------------------------
print("Настройка героя.")
print("Здоровье, сила, ловкость, выносливость — по одному числу в строке:")
health = int(input())
strength = int(input())
agility = int(input())
will = int(input())

# --- Расчёт урона ----------------------------------
base_attack = 10
damage = base_attack + strength * 1.5
crit_damage = damage * 2
stamina = agility / damage

# --- Формуляр героя --------------------------------
print("Характеристики героя:")
print(f"Здоровье: {health}")
print(f"Сила: {strength}")
print(f"Ловкость: {agility}")
print(f'Воля: {will}')
print()
print(f"Урон героя: {damage:.1f}")
print(f'Стамина героя: {stamina}')
print(f"Критический урон: {crit_damage:.1f}")
print()

# --- Меню действий ---------------------------------
print("Что делаешь?")
print("1 - осмотреться")
print("2 - идти вперёд")
print("3 - отдохнуть")
print("4 - посмотреть на карту")
print("5 - разжечь костер")
# пункты 4 и 5 — твои, по одной строке print на каждый
print()

# --- Выбор действия --------------------------------
choice = input()
match choice:
  case "1":
    print("Вы осмотрелись. У обрыва лежат доски.")
  case "2":
    stamina = stamina - 2
    print("Вы осторожно идёте вперёд. Доски скрипят под ногами.")
    print('Текущее состояние стамины: {stamina}')
  case '3':
    stamina = stamina + 6
    print('Вы решили вздремнуть. +6 к стамине')
    print('Текущее состояние стамины: {stamina}')
  case '4':
    print('Вы развернули карту. Вокруг лес, но рядом заброшенная деревня')
  case '5':
    stamina = stamina - 2
    print('Вы собрали доски, лежавшие у обрыва и разожгли костер')
    print('Текущее состояние стамины: {stamina}')
  case _:
    print("Такого действия нет.")

