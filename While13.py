# Дано число A (> 1). Вывести наименьшее из целых чисел K,
# для которых сумма 1 + 1/2 + ... + 1/K будет больше A, и саму эту сумму.

A = float(input("Введите число A (> 1): "))

if A <= 1:
    print("Ошибка: число должно быть больше 1.")
else:
    k = 0
    total = 0.0
    while total <= A:
        k += 1
        total += 1 / k
    print(f"Наименьшее целое K, при котором сумма 1 + 1/2 + ... + 1/K > {A}: {k}")
    print(f"Сама эта сумма: {total}")
