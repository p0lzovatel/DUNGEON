# Известно, что X кг конфет стоит A рублей. 
# Определить, сколько стоит 1 кг и Y кг этих же конфет.

X = float(input('Введите массу конфет'))
A = float(input('Введите стоимость этих конфет'))
Y = float(input('Введите вторую массу этих же конфет'))

sum1 = A / X
sum2 = sum1 * Y

print(f'стоимость конфет за 1 кг: {sum1}')
print(f'стоимость конфет за Y кг: {sum2}')