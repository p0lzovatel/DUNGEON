# Прочитать строку и целое число — индекс. Вывести символ строки под этим индексом.
# Если индекса нет, вывести «Нет такого символа». Нечисловой ввод обрабатывать не требуется.

s = input()
index = int(input())
if 0 <= index < len(s):
    print(s[index])
else:
    print("Нет такого символа")
