# Даны положительные числа A и B (A > B).
# На отрезке длины A размещено максимально возможное количество отрезков длины B (без наложений).
# Не используя операции умножения и деления, найти количество отрезков B, размещенных на отрезке A.

A = float(input("Введите длину отрезка A (положительное число): "))
B = float(input("Введите длину отрезка B (положительное число, B < A): "))

if A <= 0 or B <= 0:
    print("Числа должны быть положительными.")
elif B >= A:
    print("Должно выполняться условие A > B.")
else:
    count = 0          
    remaining = A      

    
    while remaining >= B:
        remaining -= B
        count += 1

    print(f"Количество отрезков длины {B}, которые помещаются на отрезке длины {A}: {count}")
