# Читать ввод, пока не будет введено целое число.
# Некорректный ввод не роняет программу и не считается:
# печатается «Это не число. Попробуй ещё:», чтение повторяется. Вывести полученное число.

while True:
    user_input = input()
    try:
        number = int(user_input)
        break
    except ValueError:
        print("Это не число. Попробуй ещё:")
print(number)
