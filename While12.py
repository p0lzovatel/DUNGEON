# Дано целое число N (> 1). Вывести наибольшее из целых чисел K,
# для которых сумма 1 + 2 + ... + K будет меньше или равна N, и саму эту сумму.

n = int(input("Введите целое число N (> 1): "))
if n <= 1:
    print("Ошибка: число должно быть больше 1.")
else:
    k = 0
    total = 0
    while total + (k + 1) <= n:
        k += 1
        total += k
    print(f"Наибольшее K, для которого сумма 1 + 2 + ... + K ≤ {n}: {k}")
    print(f"Сама эта сумма: {total}")
