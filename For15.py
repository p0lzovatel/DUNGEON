# Дано вещественное число A и целое число N (> 0).
# Найти A в степени N: AN = A · A · ... · A (число A перемножается N раз).

A = float(input('Введите нецелое число'))
N = int(input('Введите целое положительное число'))

if N < 0:
    print('Ошибка: второе число должно быть положительным')
else:
    result = A**N
    print(f'Ответ: {result}')