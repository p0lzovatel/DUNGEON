# Дано целое число N (> 0). Найти наименьшее целое положительное число K,
# квадрат которого превосходит N: K2 > N. Функцию извлечения квадратного корня не использовать.

n = int(input("Введите целое число N (> 0): "))
if n <= 0:
    print("Ошибка: число должно быть больше 0.")
else:
    k = 1
    while k * k <= n:
        k += 1
    print(f"Наименьшее целое положительное число K, для которого K^2 > N: {k}")
