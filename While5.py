# Дано целое число N (> 0), являющееся некоторой степенью числа 2: N = 2^K.
# Найти целое число K — показатель этой степени.

n = int(input("Введите целое число N (> 0), являющееся степенью двойки: "))

k = 0
temp = n
while temp > 1:
    temp //= 2
    k += 1
print(f"Показатель степени K: {k}")
