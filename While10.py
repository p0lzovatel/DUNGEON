# Дано целое число N (> 1). Найти наибольшее целое число K,
# при котором выполняется неравенство 3^K < N.

n = int(input("Введите целое число N (> 1): "))
if n <= 1:
    print("Ошибка: число должно быть больше 1.")
else:
    k = 0
    power_of_3 = 1
    while power_of_3 * 3 < n:
        power_of_3 *= 3
        k += 1
    print(f"Наибольшее целое K, при котором 3^{k} < {n}: {k}")
