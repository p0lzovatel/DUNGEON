# Дано целое число N (> 0). Найти двойной факториал N: N!! = N·(N−2)·(N−4)·...
# (последний сомножитель равен 2, если N — четное, и 1, если N — нечетное).
# Чтобы избежать целочисленного переполнения,
# вычислять это произведение с помощью вещественной переменной и вывести его как вещественное число.

n = int(input("Введите целое число N (> 0): "))

if n <= 0:
    print("Ошибка: число должно быть больше 0.")
else:
    result = 1.0 
    current = n
    while current > 0:
        result *= current
        current -= 2
    print(f"Двойной факториал {n}!! = {result}")
